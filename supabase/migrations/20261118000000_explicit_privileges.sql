-- Make table permissions identical on every Supabase project (owner's cloud project included).
-- Supabase cloud gives signed-out (anon) and signed-in (authenticated) users ALL privileges on new tables by
-- default; the local project used for testing does not. Row-level security already limits rows, but some
-- rules rely on column-level permissions (e.g. only DoneZo's server may change a business's plan).
-- This resets everything to the exact, tested set of permissions, and stops future tables getting broad defaults.

alter default privileges for role postgres in schema public revoke all on tables from anon, authenticated;
alter default privileges for role postgres in schema public revoke all on sequences from anon, authenticated;
revoke all on all tables in schema public from anon, authenticated;
revoke all on all sequences in schema public from anon, authenticated;

